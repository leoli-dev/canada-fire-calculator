import { expect, test, type Page } from '@playwright/test'
import { chooseMode } from './fixtures/app-bar'
import { revealProfessionalEditor } from './fixtures/professional'
const saved = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fire-inputs')!).state)
async function enter(page: Page, path: string, field: string, value: string) {
  await page.goto(`/#/guided/${path}`)
  const input = page.locator(`[data-field="${field}"] input`)
  await input.fill(value)
  await input.blur()
}
async function confirmPartner(page: Page, age: string, cpp: string, oas: string) {
  await enter(page, 'family/family.ages', 'partner.currentAge', age)
  await enter(page, 'income/cpp.partner', 'partner.cppAnnualAt65', cpp)
  await enter(page, 'income/oas.partner', 'partner.oasAnnualAt65', oas)
}
const partner = (state: any) => state.canonical.people.find((person: any) => person.role === 'partner')
const sources = (state: any, id: string) => state.canonical.incomeSources.filter((source: any) => source.recipientId === id || source.id.startsWith(`${id}:`))
const amounts = (rows: any[]) => Object.fromEntries(rows.filter(row => row.kind === 'cpp' || row.kind === 'oas').map(row => [row.kind, row.annualAmount]))
const partnerMeta = (state: any) => Object.fromEntries(Object.entries(state.answerMeta).filter(([key]) => key.startsWith('partner.')))

for (const settle of [true, false]) test(`partner ${settle ? 'explicit settlement discards' : 'ordinary Single round trip retains'} confirmation ownership across reload`, async ({ page }, info) => {
  await page.goto('/#/guided/family/family.people')
  await page.getByRole('radio', { name: 'Couple (combined) Plan with my partner', exact: true }).check()
  await confirmPartner(page, '52', '975', '875')
  const original = await saved(page)
  const originalPartner = partner(original)
  const originalSources = sources(original, originalPartner.id)
  expect(originalPartner).toMatchObject({ ageInBaseYear: 52, cppAnnualAt65: 975, oasAnnualAt65: 875, cppAmountSource: { source: 'manual' }, oasAmountSource: { source: 'manual' } })
  expect(amounts(originalSources)).toEqual({ cpp: { status: 'known', value: 975 }, oas: { status: 'known', value: 875 } })
  for (const key of ['partner.currentAge', 'partner.cppAnnualAt65', 'partner.oasAnnualAt65']) expect(original.answerMeta[key]).toMatchObject({ status: 'confirmed', origin: 'user' })
  expect(original.inputs.partner).toMatchObject({ currentAge: 52, cppAnnualAt65: 975, oasAnnualAt65: 875, cppAmountSource: { source: 'manual' }, oasAmountSource: { source: 'manual' } })
  await chooseMode(page, 'professional')
  const profile = page.locator('[data-group="profile"]')
  const profileSummary = profile.locator(':scope > summary small')
  const benefitsSummary = page.locator('[data-group="benefits"] > summary small')
  await expect(profileSummary).toContainText('2 of 6 tracked answers confirmed')
  await expect(benefitsSummary).toContainText('2 of 8 tracked answers confirmed')
  await revealProfessionalEditor(page, profile)
  await profile.locator('select').last().selectOption('single')
  const removed = await saved(page)
  expect(removed.canonical.orphanedPeople.find((person: any) => person.id === originalPartner.id)).toEqual(originalPartner)
  expect(partnerMeta(removed)).toEqual(partnerMeta(original))
  if (settle) {
    await page.getByTestId('migration-settle-single').click()
    const settled = await saved(page)
    expect(settled.canonical.orphanedPeople).toBeUndefined()
    expect(sources(settled, originalPartner.id)).toEqual([])
    expect(settled.canonical.people).toHaveLength(1)
  }
  await page.reload()
  await revealProfessionalEditor(page, profile)
  await profile.locator('select').last().selectOption('couple')
  const returned = await saved(page)
  await page.reload()
  const restored = await saved(page)
  expect(restored.inputs).toEqual(returned.inputs)
  expect(restored.canonical).toEqual(returned.canonical)
  expect(restored.answerMeta).toEqual(returned.answerMeta)
  const newPartner = partner(restored)
  const summary = { profile: await profileSummary.textContent(), benefits: await benefitsSummary.textContent() }
  await info.attach('settlement-before-after', { body: JSON.stringify({ settle, originalPartner, originalSources, originalPartnerMeta: partnerMeta(original), returnedPartner: newPartner, returnedSources: sources(restored, newPartner.id), returnedPartnerMeta: partnerMeta(restored), returnedLegacyPartner: restored.inputs.partner, summary }), contentType: 'application/json' })
  if (!settle) {
    expect(newPartner).toEqual(originalPartner)
    expect(sources(restored, newPartner.id)).toEqual(originalSources)
    expect(partnerMeta(restored)).toEqual(partnerMeta(original))
    expect(restored.inputs.partner).toMatchObject({ currentAge: 52, cppAnnualAt65: 975, oasAnnualAt65: 875, cppAmountSource: { source: 'manual' }, oasAmountSource: { source: 'manual' } })
    await expect(profileSummary).toContainText('2 of 6 tracked answers confirmed')
    await expect(benefitsSummary).toContainText('2 of 8 tracked answers confirmed')
    return
  }
  expect(restored.inputs.partner).toMatchObject({ currentAge: 35, cppAnnualAt65: 10000, oasAnnualAt65: 8700 })
  expect(newPartner).toMatchObject({ ageInBaseYear: 35, cppAnnualAt65: 10000, oasAnnualAt65: 8700 })
  expect(newPartner.cppAmountSource).toBeUndefined()
  expect(newPartner.oasAmountSource).toBeUndefined()
  expect(amounts(sources(restored, newPartner.id))).toEqual({ cpp: { status: 'known', value: 10000 }, oas: { status: 'known', value: 8700 } })
  expect(restored.inputs.partner.cppAmountSource).toBeUndefined()
  expect(restored.inputs.partner.oasAmountSource).toBeUndefined()
  for (const meta of Object.values(partnerMeta(restored)) as Array<{ status: string }>) expect(['confirmed', 'estimated']).not.toContain(meta.status)
  await expect(profileSummary).toContainText('1 of 6 tracked answers confirmed')
  await expect(benefitsSummary).toHaveText('Needs review')
  // The same reusable slot/ID must not substitute for confirmation ownership.
  expect(newPartner.id).toBe(originalPartner.id)
  await chooseMode(page, 'guided')
  await confirmPartner(page, '44', '1250', '1125')
  await chooseMode(page, 'professional')
  const fresh = await saved(page)
  const freshPerson = partner(fresh)
  expect(freshPerson).toMatchObject({ ageInBaseYear: 44, cppAnnualAt65: 1250, oasAnnualAt65: 1125, cppAmountSource: { source: 'manual' }, oasAmountSource: { source: 'manual' } })
  expect(amounts(sources(fresh, freshPerson.id))).toEqual({ cpp: { status: 'known', value: 1250 }, oas: { status: 'known', value: 1125 } })
  await info.attach('fresh-confirmations', { body: JSON.stringify({ freshPerson, freshSources: sources(fresh, freshPerson.id), freshPartnerMeta: partnerMeta(fresh) }), contentType: 'application/json' })
  expect(fresh.inputs.partner).toMatchObject({ currentAge: 44, cppAnnualAt65: 1250, oasAnnualAt65: 1125, cppAmountSource: { source: 'manual' }, oasAmountSource: { source: 'manual' } })
  for (const key of ['partner.currentAge', 'partner.cppAnnualAt65', 'partner.oasAnnualAt65']) {
    expect(fresh.answerMeta[key]).toMatchObject({ status: 'confirmed', origin: 'user' })
    expect(fresh.answerMeta[key].updatedAt).not.toBe(original.answerMeta[key].updatedAt)
  }
  await expect(profileSummary).toContainText('2 of 6 tracked answers confirmed')
  await expect(benefitsSummary).toContainText('2 of 8 tracked answers confirmed')
  await page.reload()
  const reloaded = await saved(page)
  expect(reloaded.canonical).toEqual(fresh.canonical)
  expect(reloaded.inputs).toEqual(fresh.inputs)
  expect(reloaded.answerMeta).toEqual(fresh.answerMeta)
  await expect(profileSummary).toContainText('2 of 6 tracked answers confirmed')
  await expect(benefitsSummary).toContainText('2 of 8 tracked answers confirmed')
})
