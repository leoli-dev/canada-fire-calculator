import { expect, test } from '@playwright/test'
import { chooseMode } from './fixtures/app-bar'
import { prepareProfessionalTarget } from './fixtures/professional'

const saved = (page: import('@playwright/test').Page) => page.evaluate(() => JSON.parse(localStorage.getItem('fire-inputs')!).state)

test('Guided confirmed 725k rental cannot confirm its default 500k replacement or a shifted rental', async ({ page }) => {
  await page.goto('/#/guided/housing/housing.other')
  await page.getByRole('radio', { name: 'Include a rental property', exact: true }).check()
  await page.getByRole('radio', { name: 'No other loans', exact: true }).check()
  await page.goto('/#/guided/housing/rental.0.value')
  await page.locator('[data-field="investmentProperties.0.value"] input').fill('725000')
  await page.locator('[data-field="investmentProperties.0.value"] input').blur()
  const original = await saved(page)
  expect(original.answerMeta['investmentProperties.0.value']).toMatchObject({ status: 'confirmed', origin: 'user' })
  await chooseMode(page, 'professional')
  const housing = page.locator('[data-group="housing"]')
  const summary = housing.locator(':scope > summary small')
  await (await prepareProfessionalTarget(housing.getByRole('button', { name: 'Remove', exact: true }), housing.getByRole('button', { name: 'Remove', exact: true, includeHidden: true }))).click()
  await (await prepareProfessionalTarget(housing.getByRole('button', { name: '+ Investment property', exact: true }), housing.getByRole('button', { name: '+ Investment property', exact: true, includeHidden: true }))).click()
  await expect(summary).toHaveText('Needs review')
  const replacement = await saved(page)
  expect(replacement.inputs.investmentProperties[0].value).toBe(500000)
  expect(replacement.canonical.properties.filter((property: { kind: string }) => property.kind === 'investment')[0].value).toBe(500000)
  expect(replacement.answerMeta).toEqual(original.answerMeta)
  await page.reload()
  await expect(summary).toHaveText('Needs review')
  await prepareProfessionalTarget(housing.getByRole('button', { name: '+ Investment property', exact: true }), housing.getByRole('button', { name: '+ Investment property', exact: true, includeHidden: true }))
  // Shift a second entity into the same positional key; stale metadata still cannot identify it.
  await housing.getByRole('button', { name: '+ Investment property', exact: true }).click()
  const rentals = housing.locator('.property-card').filter({ hasText: 'Investment property' })
  await rentals.nth(1).locator('label.field').filter({ hasText: 'Current value' }).locator('input').fill('850000')
  await rentals.nth(1).locator('label.field').filter({ hasText: 'Current value' }).locator('input').blur()
  await rentals.first().getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(summary).toHaveText('Needs review')
  await page.reload()
  expect((await saved(page)).inputs.investmentProperties[0].value).toBe(850000)
  expect((await saved(page)).answerMeta).toEqual(original.answerMeta)
  await expect(summary).toHaveText('Needs review')
})

test('Guided confirmed debt cannot confirm a replacement or a shifted debt', async ({ page }) => {
  await page.goto('/#/guided/housing/housing.other')
  await page.getByRole('radio', { name: 'No rental property', exact: true }).check()
  await page.getByRole('radio', { name: 'Include another loan', exact: true }).check()
  await page.goto('/#/guided/housing/debt.0.balance')
  await page.locator('[data-field="debts.0.balance"] input').fill('72500')
  await page.locator('[data-field="debts.0.balance"] input').blur()
  const original = await saved(page)
  expect(original.answerMeta['debts.0.balance']).toMatchObject({ status: 'confirmed', origin: 'user' })
  await chooseMode(page, 'professional')
  const housing = page.locator('[data-group="housing"]')
  const summary = housing.locator(':scope > summary small')
  const debts = housing.locator('.property-card')
  await (await prepareProfessionalTarget(debts.first().getByRole('button', { name: 'Remove', exact: true }), debts.first().getByRole('button', { name: 'Remove', exact: true, includeHidden: true }))).click()
  await housing.getByRole('button', { name: '+ Add debt', exact: true }).click()
  await expect(summary).toHaveText('Needs review')
  expect((await saved(page)).answerMeta).toEqual(original.answerMeta)
  await housing.getByRole('button', { name: '+ Add debt', exact: true }).click()
  await debts.nth(1).locator('label.field').filter({ hasText: 'Current balance' }).locator('input').fill('85000')
  await debts.nth(1).locator('label.field').filter({ hasText: 'Current balance' }).locator('input').blur()
  await debts.first().getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(summary).toHaveText('Needs review')
  await page.reload()
  expect((await saved(page)).inputs.debts[0].balance).toBe(85000)
  expect((await saved(page)).answerMeta).toEqual(original.answerMeta)
  await expect(summary).toHaveText('Needs review')
})
