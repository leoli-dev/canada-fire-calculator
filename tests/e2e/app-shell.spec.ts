import { expect, test } from '@playwright/test'
import { chooseLanguage, chooseMode } from './fixtures/app-bar'

test('shell puts the first question within 200px and retains focused headings without a programmatic ring', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const title = page.locator('#question-title')
  await expect(title).toBeFocused()
  await expect(title).toHaveCSS('box-shadow', 'none')
  expect((await title.boundingBox())!.y).toBeLessThanOrEqual(200)
  await expect(page.getByTestId('canonical-evidence')).toHaveCount(0)
  await page.locator('.question-pager button').last().click()
  await expect(title).toBeFocused()
  await expect(title).toHaveCSS('box-shadow', 'none')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement!.matches(':focus-visible'))).toBe(true)
  expect(await page.evaluate(() => getComputedStyle(document.activeElement!).boxShadow)).not.toBe('none')
  await testInfo.attach('phone-first-question.png', { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' })
})

test('mobile shell menu closes with Escape and returns focus, while mode and privacy actions remain reachable', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  const menu = page.getByTestId('app-menu')
  await menu.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Menu' })
  await expect(dialog.getByText('Privacy settings')).toBeVisible()
  await expect(dialog.getByTestId('analytics-menu-footer')).toBeVisible()
  await expect(dialog.getByRole('link', { name: /GitHub/ })).toBeVisible()
  await expect(dialog.getByRole('button', { name: "See what's simplified" })).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: "See what's simplified" })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await chooseMode(page, 'professional')
  await expect(page.locator('.input-form')).toBeVisible()
  await expect(page.getByTestId('canonical-evidence')).toBeVisible()
  await chooseMode(page, 'guided')
  await expect(page.getByTestId('canonical-evidence')).toHaveCount(0)
  await page.goto('/#/guided/review')
  await expect(page.getByTestId('canonical-evidence')).toBeVisible()
})

test('desktop rails follow the breakpoint and localized directory labels fit without truncation', async ({ page }, testInfo) => {
  await page.goto('/')
  const measurements = []
  for (const [language, width] of [['EN', 1440], ['FR', 320], ['中文', 390]] as const) {
    await page.setViewportSize({ width, height: 844 })
    await chooseLanguage(page, language)
    if (width <= 640) await page.locator('.mobile-directory-trigger').click()
    for (const label of await page.locator('.category-navigation details[open] button > span:not(.sr-only)').all()) {
      const style = await label.evaluate(element => ({ overflow: getComputedStyle(element).textOverflow, width: element.clientWidth, scrollWidth: element.scrollWidth }))
      expect(style.overflow).not.toBe('ellipsis')
      expect(style.scrollWidth).toBeLessThanOrEqual(style.width)
    }
    if (width <= 640) await page.locator('.directory-close').click()
    const metric = await page.evaluate(() => ({ width: innerWidth, titleTop: document.querySelector('#question-title')!.getBoundingClientRect().top, overflow: document.documentElement.scrollWidth > innerWidth, headerHeight: document.querySelector('.app-bar')!.getBoundingClientRect().height }))
    expect(metric.overflow).toBe(false)
    if (width === 390) expect(metric.titleTop).toBeLessThanOrEqual(200)
    measurements.push({ language, ...metric })
    await testInfo.attach(`shell-${language}-${width}.png`, { body: await page.screenshot({ animations: 'disabled' }), contentType: 'image/png' })
  }
  await page.setViewportSize({ width: 1280, height: 844 })
  await expect(page.locator('.question-help-rail')).toBeVisible()
  await page.setViewportSize({ width: 1100, height: 844 })
  await expect(page.locator('.question-help-rail')).toBeHidden()
  await expect(page.locator('.directory-shell')).toBeVisible()
  await page.setViewportSize({ width: 1099, height: 844 })
  await expect(page.locator('.directory-shell')).toBeHidden()
  await expect(page.locator('.mobile-directory-trigger')).toBeVisible()
  await testInfo.attach('shell-metrics.json', { body: JSON.stringify(measurements, null, 2), contentType: 'application/json' })
})
