import { prepareProfessionalTarget } from './fixtures/professional'
import { expect, test } from '@playwright/test'
import { chooseMode } from './fixtures/app-bar'
import { canonicalAppPlan } from './fixtures/canonical-app-plan'

test('phone Professional tab keys and sequential focus reach the labelled selected pane without losing scroll', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await chooseMode(page, 'professional')
  const tabs = page.getByRole('tablist', { name: 'Plan views' })
  const inputs = tabs.getByRole('tab', { name: 'Inputs', exact: true })
  const results = tabs.getByRole('tab', { name: 'Results', exact: true })
  const inputPanel = page.getByRole('tabpanel', { name: 'Inputs', exact: true })
  const resultPanel = page.getByRole('tabpanel', { name: 'Results', exact: true })
  await inputPanel.evaluate(element => { element.scrollTop = 230 })
  await (await prepareProfessionalTarget(inputs)).focus()
  await page.keyboard.press('ArrowRight')
  await expect(results).toBeFocused()
  await expect(results).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Tab')
  await expect(resultPanel).toBeFocused()
  await resultPanel.evaluate(element => { element.scrollTop = 400 })
  await page.keyboard.press('Shift+Tab')
  await expect(results).toBeFocused()
  await page.keyboard.press('Home')
  await expect(inputs).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(inputPanel).toBeFocused()
  expect(await inputPanel.evaluate(element => element.scrollTop)).toBe(230)
  await page.keyboard.press('Shift+Tab')
  await expect(inputs).toBeFocused()
  await page.keyboard.press('End')
  await expect(results).toBeFocused()
  expect(await resultPanel.evaluate(element => element.scrollTop)).toBe(400)
  await (await prepareProfessionalTarget(inputs)).click()
  await (await prepareProfessionalTarget(results)).click()
  await expect(results).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(resultPanel).toBeFocused()
  expect(await resultPanel.evaluate(element => element.scrollTop)).toBe(400)
})

for (const variant of ['settled', 'no-opt-in'] as const) test(`phone Guided ${variant} tabs restore scrolling with visible focus and retain fresh route focus`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const plan = canonicalAppPlan(variant)
  Object.assign(plan.state, { entryMode: 'guided', guidedView: 'results', resultRevision: 23 })
  await page.addInitScript(value => localStorage.setItem('fire-inputs', JSON.stringify(value)), plan)
  await page.goto('/#/guided/results')
  await expect(page.locator('.results-intro h2')).toBeFocused()
  const before = await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('fire-inputs')!).state; return [s.inputs, s.canonical, s.answerMeta, s.questionAnswers, s.inputRevision, s.resultRevision] })
  const answers = page.getByRole('tab', { name: 'Answers', exact: true })
  const results = page.getByRole('tab', { name: 'Results', exact: true })
  const resultScroll = await page.evaluate(() => { window.scrollTo(0, 500); return scrollY })
  await (await prepareProfessionalTarget(answers)).click()
  await expect(answers).toBeFocused()
  const reviewScroll = await page.evaluate(() => { window.scrollTo(0, 330); return scrollY })
  await page.keyboard.press('ArrowRight')
  await expect(results).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(resultScroll)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tabpanel', { name: 'Results', exact: true })).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(resultScroll)
  const focusedVisible = await page.evaluate(() => { const box = document.activeElement!.getBoundingClientRect(); return box.bottom > 0 && box.top < innerHeight })
  expect(focusedVisible).toBe(true)
  await page.keyboard.press('Shift+Tab')
  await expect(results).toBeFocused()
  await page.keyboard.press('Home')
  await expect(answers).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(reviewScroll)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tabpanel', { name: 'Answers', exact: true })).toBeFocused()
  const after = await page.evaluate(() => { const s = JSON.parse(localStorage.getItem('fire-inputs')!).state; return [s.inputs, s.canonical, s.answerMeta, s.questionAnswers, s.inputRevision, s.resultRevision] })
  expect(after).toEqual(before)
  await page.goto('/#/guided/review')
  await page.reload()
  await expect(page.locator('.answer-review h2')).toBeFocused()
})
