test('no-edit professional blur preserves estimate and revision; actual edits commit once', async ({ page }) => {
  test.setTimeout(60_000)
  await page.getByRole('button', { name: 'Professional', exact: true }).click()
  await page.evaluate(() => {
    const stored = JSON.parse(localStorage.getItem('fire-inputs')!)
    stored.state.answerMeta.annualSavings = { status: 'estimated', origin: 'default', updatedAt: new Date().toISOString(), assumptionValue: 40000 }
    localStorage.setItem('fire-inputs', JSON.stringify(stored))
  })
  await page.reload()
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('fire-inputs')!).state)
  const savings = page.locator('label.field').filter({ hasText: 'Annual after-tax savings' }).locator('input')
  await page.getByRole('button', { name: 'Run 1,000 simulations' }).click()
  await expect(page.locator('.mc-rate')).toBeVisible({ timeout: 45_000 })
  const before = await read()
  await savings.focus()
  await savings.blur()
  let after = await read()
  expect(after.inputRevision).toBe(before.inputRevision)
  expect(after.answerMeta.annualSavings).toEqual(before.answerMeta.annualSavings)
  await expect(page.locator('.mc-rate')).toBeVisible()
  await savings.fill('24000')
  await savings.blur()
  after = await read()
  expect(after.inputRevision).toBe(before.inputRevision + 1)
  expect(after.answerMeta.annualSavings.status).toBe('confirmed')
  const age = page.locator('label.field').filter({ hasText: 'Current age' }).locator('input')
  await age.fill('250')
  expect((await read()).inputRevision).toBe(after.inputRevision + 1)
  await age.blur()
  expect((await read()).inputRevision).toBe(after.inputRevision + 1)
})

test('guided monthly no-edit blur preserves exact annual amount and estimate', async ({ page }) => {
  await page.goto('/#/guided/saving/saving.method')
  await page.getByRole('radio', { name: /monthly amount/ }).check()
  await page.evaluate(() => {
    const stored = JSON.parse(localStorage.getItem('fire-inputs')!)
    stored.state.answerMeta.annualSavings = { status: 'estimated', origin: 'default', updatedAt: new Date().toISOString(), assumptionValue: 40000 }
    localStorage.setItem('fire-inputs', JSON.stringify(stored))
  })
  await page.reload()
  await page.goto('/#/guided/saving/saving.amount')
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('fire-inputs')!).state)
  const before = await read()
  const savings = page.locator('[data-field="annualSavings"] input')
  await savings.focus()
  await savings.blur()
  let after = await read()
  expect(after.inputs.annualSavings).toBe(40000)
  expect(after.inputRevision).toBe(before.inputRevision)
  expect(after.answerMeta.annualSavings).toEqual(before.answerMeta.annualSavings)
  await savings.fill('3333.33')
  await savings.blur()
  after = await read()
  expect(after.inputs.annualSavings).toBe(39999.96)
  expect(after.inputRevision).toBe(before.inputRevision + 1)
  await page.reload()
  expect((await read()).inputs.annualSavings).toBe(39999.96)
  await page.getByRole('button', { name: 'Professional', exact: true }).click()
  await page.getByRole('button', { name: 'Guided', exact: true }).click()
  expect((await read()).inputs.annualSavings).toBe(39999.96)
})

